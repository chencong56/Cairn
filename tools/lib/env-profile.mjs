/**
 * 开发画像：公开文件 + 密钥文件的对齐、合并与发布端口黑名单。
 * 进程只读仓库根 `.env`（由 use / dev:env 合并写出）。
 */
export const SECRET_KEYS = [
  'CAIRN_DB_PASSWORD',
  'CAIRN_JWT_SECRET',
  'CAIRN_CREDENTIAL_KEY',
  'CAIRN_INTERNAL_AUTH_SECRET',
  'CAIRN_S3_ACCESS_KEY',
  'CAIRN_S3_SECRET_KEY',
]

export const SECRET_KEY_SET = new Set(SECRET_KEYS)

const KEY_LINE = /^[ \t]*#?[ \t]*([A-Z][A-Z0-9_]*)[ \t]*=/gm
const ACTIVE_HEADER = /^# cairn-env-active: ([a-z][a-z0-9-]*)\s*$/m
const TARGET_SECRET_LINE = /PASSWORD|SECRET|ACCESS_KEY|CREDENTIAL/i

export function keysOf(text) {
  return new Set([...text.matchAll(KEY_LINE)].map((match) => match[1]))
}

export function assignmentValue(text, key) {
  const match = text.match(new RegExp(`^${key}=(.*)$`, 'm'))
  if (!match) return ''
  return match[1].replace(/\s+#.*$/, '').trim()
}

export function alignText(exampleText, profileText) {
  const exampleKeys = keysOf(exampleText)
  const profileKeys = keysOf(profileText)
  return {
    missing: [...exampleKeys].filter((key) => !profileKeys.has(key)),
    extra: [...profileKeys].filter((key) => !exampleKeys.has(key)),
  }
}

export function secretKeysIn(text) {
  return SECRET_KEYS.filter((key) => keysOf(text).has(key))
}

export function inspectSecretsFile(secretsText) {
  const keys = keysOf(secretsText)
  return {
    extra: [...keys].filter((key) => !SECRET_KEY_SET.has(key)),
    missing: SECRET_KEYS.filter((key) => !keys.has(key)),
    empty: SECRET_KEYS.filter((key) => keys.has(key) && assignmentValue(secretsText, key) === ''),
  }
}

export function alignPublicAndSecrets(exampleText, publicText, secretsText) {
  const union = new Set([...keysOf(publicText), ...keysOf(secretsText)])
  const exampleKeys = keysOf(exampleText)
  return {
    missing: [...exampleKeys].filter((key) => !union.has(key)),
    extra: [...union].filter((key) => !exampleKeys.has(key)),
  }
}

export function mergeProfile(name, publicText, secretsText) {
  const secretBlock = SECRET_KEYS.map((key) => `${key}=${assignmentValue(secretsText, key)}`).join('\n')
  return (
    `# cairn-env-active: ${name}\n` +
    `# generated by pnpm dev:env / pnpm env:use — do not edit\n\n` +
    `${publicText.replace(/\s+$/, '')}\n\n` +
    `# --- secrets (from .env.${name}.secrets) ---\n` +
    `${secretBlock}\n`
  )
}

export function readActiveProfileName(envText, symlinkTarget) {
  const header = envText.match(ACTIVE_HEADER)
  if (header) return header[1]
  if (symlinkTarget) {
    const match = String(symlinkTarget).match(/^\.env\.(.+)$/)
    return match?.[1] ?? symlinkTarget
  }
  return '(regular file)'
}

export function summarizeEnv(text) {
  const host = assignmentValue(text, 'CAIRN_DB_HOST')
  const port = assignmentValue(text, 'CAIRN_DB_PORT') || '5432'
  const name = assignmentValue(text, 'CAIRN_DB_NAME')
  const store = assignmentValue(text, 'CAIRN_OBJECT_STORE') || 'local'
  const object =
    store === 's3'
      ? `s3 ${assignmentValue(text, 'CAIRN_S3_ENDPOINT')} / ${assignmentValue(text, 'CAIRN_S3_BUCKET')}`
      : `local ${assignmentValue(text, 'CAIRN_OBJECT_STORE_DIR') || '.data/object-store'}`
  const hint = assignmentValue(text, 'CAIRN_CHANGE_HINT') || 'auto'
  const redis = assignmentValue(text, 'CAIRN_REDIS_URL')
  const displayRedis = redis.replace(/:\/\/[^@/]+@/, '://***@')
  const webPort = assignmentValue(text, 'CAIRN_WEB_PORT') || '5173'
  return {
    database: `${host}:${port}/${name}`,
    object,
    changeHint: `${hint}${displayRedis ? ` (redis: ${displayRedis})` : ''}`,
    webUrl: `http://127.0.0.1:${webPort}`,
    dbHost: host,
    dbPort: port,
    redisUrl: redis,
    s3Endpoint: assignmentValue(text, 'CAIRN_S3_ENDPOINT'),
  }
}

export function parseHostPort(host, port, fallbackPort) {
  const hostname = String(host ?? '').trim().toLowerCase()
  const parsedPort = Number(String(port ?? '').trim() || fallbackPort)
  if (!hostname || !Number.isInteger(parsedPort) || parsedPort <= 0) return null
  return { hostname, port: parsedPort }
}

export function parseUrlHostPort(raw, defaultPort) {
  const value = String(raw ?? '').trim()
  if (!value) return null
  try {
    const url = new URL(value)
    const port = Number(url.port) || defaultPort || (url.protocol === 'https:' ? 443 : 80)
    if (!url.hostname || !Number.isInteger(port) || port <= 0) return null
    return { hostname: url.hostname.toLowerCase(), port }
  } catch {
    return null
  }
}

export function hitsPublishGuard(values, guard) {
  const endpoints = []
  const db = parseHostPort(values.dbHost, values.dbPort, 5432)
  if (db) endpoints.push({ ...db, name: 'database' })
  const redis = parseUrlHostPort(values.redisUrl, 6379)
  if (redis) endpoints.push({ ...redis, name: 'redis' })
  const s3 = parseUrlHostPort(values.s3Endpoint, 80)
  if (s3) endpoints.push({ ...s3, name: 's3' })

  for (const rule of guard.publish ?? []) {
    const hosts = (rule.hosts ?? []).map((host) => String(host).toLowerCase())
    const ports = (rule.ports ?? []).map(Number)
    for (const endpoint of endpoints) {
      if (hosts.includes(endpoint.hostname) && ports.includes(endpoint.port)) {
        return {
          hit: true,
          reason: `${endpoint.name} ${endpoint.hostname}:${endpoint.port} 是发布环境（${rule.name}），开发请用专用组件`,
        }
      }
    }
  }
  return { hit: false, reason: '' }
}

export function forbiddenSecretLinesInTarget(text) {
  return text
    .split('\n')
    .map((line, index) => ({ line, index: index + 1 }))
    .filter(({ line }) => {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#')) return false
      return TARGET_SECRET_LINE.test(trimmed)
    })
}

export function applyTestDbPin(env, options = {}) {
  if (env.CAIRN_TEST_DB_PINNED === '1') return env
  const ci = options.ci ?? Boolean(env.CI)
  const testPort = env.CAIRN_TEST_DB_PORT?.trim()
  if (!testPort) {
    if (ci) return env
    throw new Error(
      '集成测试必须连测试专用 PostgreSQL，但未配置 CAIRN_TEST_DB_PORT（见 .env.example）。\n' +
        '启动：pnpm infra:up（会同时启动 cairn-postgres-test）。不会回退到开发库。',
    )
  }
  if (ci) {
    if (testPort === String(env.CAIRN_DB_PORT ?? '')) {
      throw new Error(
        `CAIRN_TEST_DB_PORT（${testPort}）与开发库端口 CAIRN_DB_PORT 相同，测试会写进开发库，已拒绝。`,
      )
    }
    env.CAIRN_DB_PORT = testPort
    env.CAIRN_TEST_DB_PINNED = '1'
    return env
  }
  const testHost = env.CAIRN_TEST_DB_HOST?.trim() || '127.0.0.1'
  const origin = `${env.CAIRN_DB_HOST ?? ''}:${env.CAIRN_DB_PORT ?? ''}`
  const pinned = `${testHost}:${testPort}`
  if (pinned === origin) {
    throw new Error(
      `测试库 ${pinned} 与开发库相同，测试会写进开发库，已拒绝。`,
    )
  }
  env.CAIRN_DB_HOST = testHost
  env.CAIRN_DB_PORT = testPort
  env.CAIRN_TEST_DB_PINNED = '1'
  return env
}
